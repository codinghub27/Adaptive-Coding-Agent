"""Structured result schemas produced by the Phase 07 specialized agents.

These models are **structured data, not prose**: they are the typed output
of the DSA solver, debugger, explainer, and reviewer subgraphs. Phase 08's
response generator consumes them to build the final natural-language reply
that is actually shown to the learner; nothing in this module is itself a
finished response.

Many fields here hold free text (hints, explanations, static-analysis
messages, patched code) that is either lifted directly from the learner's
own code/errors or generated by an LLM working over that untrusted context.
Treat all such text as **untrusted, display-only data** -- never as
instructions to any agent, matching the convention in `app.schemas.event`
and `app.schemas.input`.

The hint ladder (`HintLevel`) is a core security boundary: a low assistance
level must never leak a full solution. `HintResult` enforces this with a
validator, and `MAX_HINT_LEVEL_FOR_ASSISTANCE` is the single source of truth
callers must use to compute each turn's ceiling.
"""

from collections.abc import Mapping
from enum import IntEnum
from types import MappingProxyType
from typing import TYPE_CHECKING, Annotated, Final, Literal

from pydantic import Field, model_validator

from app.schemas.base import APIModel
from app.schemas.execution import Verdict
from app.schemas.plan import AssistanceLevel

if TYPE_CHECKING:
    from app.graph.state import AgentOutcome

__all__ = [
    "solved_from_verdict",
    "MAX_HINT_LEVEL_FOR_ASSISTANCE",
    "AgentResult",
    "BugLocation",
    "CodeStructureNode",
    "DSAResult",
    "DebugResult",
    "ExplainResult",
    "HintLevel",
    "HintResult",
    "LineExplanation",
    "ReviewCategory",
    "ReviewFinding",
    "ReviewResult",
    "ReviewSeverity",
    "StaticFinding",
]


class HintLevel(IntEnum):
    """The 7-rung hint ladder, from least to most revealing."""

    L0_NUDGE = 0
    L1_WHAT_TO_TRACK = 1
    L2_DATA_STRUCTURE = 2
    L3_CONCRETE_IDEA = 3
    L4_PSEUDOCODE = 4
    L5_PARTIAL = 5
    L6_FULL = 6


MAX_HINT_LEVEL_FOR_ASSISTANCE: Final[Mapping[AssistanceLevel, HintLevel]] = MappingProxyType(
    {
        "hint": HintLevel.L2_DATA_STRUCTURE,
        "concept": HintLevel.L3_CONCRETE_IDEA,
        "pseudocode": HintLevel.L4_PSEUDOCODE,
        "partial": HintLevel.L5_PARTIAL,
        "full": HintLevel.L6_FULL,
    }
)
"""The single source of truth for each `AssistanceLevel`'s hint-ladder ceiling."""

ReviewSeverity = Literal["info", "minor", "major"]


class HintResult(APIModel):
    """One rung of the hint ladder produced for this turn.

    `text` is LLM-generated hint content derived from the learner's problem
    and code; treat it as untrusted, display-only data.
    """

    level: HintLevel
    text: str = Field(min_length=1)
    is_terminal: bool
    reveals_code: bool
    ceiling: HintLevel

    @model_validator(mode="after")
    def _check_ladder_invariants(self) -> "HintResult":
        if self.level > self.ceiling:
            raise ValueError("hint level must not exceed this turn's ceiling")
        if self.reveals_code and self.level < HintLevel.L5_PARTIAL:
            raise ValueError("reveals_code may only be true at L5 (partial) or L6 (full)")
        return self


class StaticFinding(APIModel):
    """A single static-analysis finding about the learner's submitted code.

    `message` is analysis output generated from untrusted user code; treat
    it as display-only data.
    """

    tool: str = Field(min_length=1, description="Which static check produced this, e.g. 'ast'.")
    message: str = Field(min_length=1)
    lineno: int | None = Field(default=None, ge=1)
    severity: ReviewSeverity = "info"


class BugLocation(APIModel):
    """Where a bug was localized in the learner's submitted code."""

    lineno: int | None = Field(default=None, ge=1)
    symbol: str | None = None


class DSAResult(APIModel):
    """Structured teaching-pipeline output for a DSA problem-solving turn.

    Free-text stage fields (`understanding`, `brute_force`, `pseudocode`,
    `code`, etc.) hold LLM-generated content grounded in the learner's
    (untrusted) problem statement and code; treat them as display-only data.
    """

    # Discriminator for the `AgentResult` union below -- required because the
    # four result models otherwise have all-optional fields, which would make
    # an untagged union ambiguous on revalidation.
    kind: Literal["dsa"] = "dsa"
    topic: str | None = Field(default=None, max_length=64)
    pattern: str | None = Field(default=None, max_length=64)
    hint: HintResult | None = None
    understanding: str | None = None
    constraints: list[str] = Field(default_factory=list[str])
    brute_force: str | None = None
    why_slow: str | None = None
    key_insight: str | None = None
    pseudocode: str | None = None
    code: str | None = None
    complexity_time: str | None = None
    complexity_space: str | None = None
    common_mistakes: list[str] = Field(default_factory=list[str])
    citations: list[str] = Field(
        default_factory=list[str], description="Knowledge-chunk ids cited for this result."
    )

    @model_validator(mode="after")
    def _code_requires_full_hint_level(self) -> "DSAResult":
        if self.code is not None and (self.hint is None or self.hint.level < HintLevel.L6_FULL):
            raise ValueError("code must be None unless the hint level reached is 6 (full)")
        return self

    def to_outcome(self) -> "AgentOutcome":
        """Project this result onto the Phase 04 `AgentOutcome` shape.

        `hints_used` is the count of ladder rungs reached this turn
        (`level + 1`); `needed_full_solution` is true only when the ladder
        actually reached L6. `solved` is left `None`: this result carries no
        direct evidence of whether the learner ultimately solved the
        problem.
        """
        from app.graph.state import AgentOutcome

        hints_used = (self.hint.level + 1) if self.hint is not None else 0
        needed_full_solution = self.hint is not None and self.hint.level >= HintLevel.L6_FULL
        text = self.hint.text if self.hint is not None else (self.understanding or "")
        return AgentOutcome(
            text=text,
            topic=self.topic,
            pattern=self.pattern,
            solved=None,
            hints_used=hints_used,
            needed_full_solution=needed_full_solution,
            errors=[],
        )


def solved_from_verdict(verdict: "Verdict | None") -> bool | None:
    """Map a sandbox `Verdict` onto `AgentOutcome.solved` without overclaiming.

    Only a **definite** verdict is evidence about the learner: "pass" -> True,
    "fail" -> False. A "skipped" or "inconclusive" verdict means nothing ran
    (no sandbox, no tests) or the run told us nothing -- that is *absence of
    evidence*, not evidence of failure, so it maps to `None`.

    This distinction is load-bearing. `update_learner_model` persists a
    learning event only when `solved is not None`, so collapsing "we could not
    check" into `False` would silently lower the learner's skill level for a
    turn in which their code was never executed.
    """
    if verdict is None or verdict.status in ("skipped", "inconclusive"):
        return None
    return verdict.status == "pass"


class DebugResult(APIModel):
    """Structured output of the debugging pipeline for a turn.

    `bug_explanation` and `patched_code` are LLM-generated from the
    learner's (untrusted) code and error output; treat them as display-only
    data. Correctness is sandbox ground truth: `fixed` can only be true when
    `final_verdict.status == "pass"`, never from an LLM's own claim.
    """

    # Discriminator for the `AgentResult` union below -- see `DSAResult.kind`.
    kind: Literal["debug"] = "debug"
    static_findings: list[StaticFinding] = Field(default_factory=list[StaticFinding])
    inferred_approach: str | None = None
    failing_case: str | None = None
    bug_explanation: str | None = None
    bug_location: BugLocation | None = None
    patched_code: str | None = None
    attempts: int = Field(default=0, ge=0)
    initial_verdict: Verdict | None = None
    final_verdict: Verdict | None = None
    fixed: bool = False

    @model_validator(mode="after")
    def _fixed_requires_passing_final_verdict(self) -> "DebugResult":
        if self.fixed and (self.final_verdict is None or self.final_verdict.status != "pass"):
            raise ValueError("fixed may only be True when final_verdict.status == 'pass'")
        return self

    def to_outcome(self) -> "AgentOutcome":
        """Project this result onto the Phase 04 `AgentOutcome` shape.

        `solved` comes from `final_verdict` (sandbox ground truth) via
        `solved_from_verdict`: `None` whenever nothing conclusive ran, so an
        unavailable sandbox is never mistaken for an observed failure.
        """
        from app.graph.state import AgentOutcome

        solved = solved_from_verdict(self.final_verdict)
        text = self.bug_explanation or self.inferred_approach or ""
        return AgentOutcome(
            text=text,
            topic=None,
            pattern=None,
            solved=solved,
            hints_used=0,
            needed_full_solution=self.patched_code is not None,
            errors=[finding.message for finding in self.static_findings],
        )


class CodeStructureNode(APIModel):
    """A node in a recursive outline of the learner's submitted code.

    `name` is taken from the (untrusted) submitted code's identifiers.
    """

    kind: Literal["module", "class", "function", "async_function", "block"]
    name: str
    lineno: int = Field(ge=1)
    end_lineno: int = Field(ge=1)
    children: list["CodeStructureNode"] = Field(default_factory=list["CodeStructureNode"])


class LineExplanation(APIModel):
    """A per-line explanation of the learner's submitted code.

    `code` is an excerpt of the learner's own (untrusted) submission;
    `explanation` is LLM-generated commentary on it. Both are display-only.
    """

    lineno: int = Field(ge=1)
    code: str
    explanation: str


class ExplainResult(APIModel):
    """Structured output of the code-explanation pipeline for a turn."""

    # Discriminator for the `AgentResult` union below -- see `DSAResult.kind`.
    kind: Literal["explain"] = "explain"
    structure: CodeStructureNode | None = None
    line_explanations: list[LineExplanation] = Field(default_factory=list[LineExplanation])
    complexity_time: str | None = None
    complexity_space: str | None = None
    complexity_rationale: str | None = None

    def to_outcome(self) -> "AgentOutcome":
        """Project this result onto the Phase 04 `AgentOutcome` shape.

        Explaining code carries no evidence of whether a problem was
        solved, so `solved` is always `None` here.
        """
        from app.graph.state import AgentOutcome

        return AgentOutcome(
            text=self.complexity_rationale or "",
            topic=None,
            pattern=None,
            solved=None,
            hints_used=0,
            needed_full_solution=False,
            errors=[],
        )


ReviewCategory = Literal[
    "correctness", "complexity", "readability", "python_practices", "edge_cases", "improvements"
]


class ReviewFinding(APIModel):
    """A single code-review finding.

    `message` and `suggestion` are LLM-generated from the learner's
    (untrusted) submitted code; treat them as display-only data.
    """

    category: ReviewCategory
    severity: ReviewSeverity
    message: str = Field(min_length=1)
    lineno: int | None = Field(default=None, ge=1)
    suggestion: str | None = None


class ReviewResult(APIModel):
    """Structured output of the code-review pipeline for a turn."""

    # Discriminator for the `AgentResult` union below -- see `DSAResult.kind`.
    kind: Literal["review"] = "review"
    correctness_verdict: Verdict | None = None
    findings: list[ReviewFinding] = Field(default_factory=list[ReviewFinding])

    @property
    def claims_correct(self) -> bool:
        """The only sanctioned way to say "this code is correct": it must be
        backed by a passing sandbox verdict, never an unverified LLM claim.
        """
        return self.correctness_verdict is not None and self.correctness_verdict.status == "pass"

    def to_outcome(self) -> "AgentOutcome":
        """Project this result onto the Phase 04 `AgentOutcome` shape.

        `solved` mirrors `claims_correct`'s evidence: `None` when no
        correctness verdict was produced this turn, otherwise the verdict's
        pass/fail.
        """
        from app.graph.state import AgentOutcome

        solved = solved_from_verdict(self.correctness_verdict)
        text = self.findings[0].message if self.findings else ""
        return AgentOutcome(
            text=text,
            topic=None,
            pattern=None,
            solved=solved,
            hints_used=0,
            needed_full_solution=False,
            errors=[finding.message for finding in self.findings if finding.severity == "major"],
        )


AgentResult = Annotated[
    DSAResult | DebugResult | ExplainResult | ReviewResult, Field(discriminator="kind")
]
"""The discriminated union of all Phase 07 agent results, tagged by `kind`.

Used by `AgentState.agent_result` so the Phase 08 response layer receives the
full structured result (not the lossy `AgentOutcome` projection), and so it
round-trips through `model_dump()`/`model_validate()` (as `run_graph` does)
without ambiguity -- all four member models have otherwise all-optional
fields, so an untagged union would silently coerce to the wrong type.
"""
